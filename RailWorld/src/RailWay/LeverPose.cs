namespace RailWorld.src.RailWay
{
    /// <summary>
    /// У якому положенні стоїть важіль стрілки. Модель важеля має два крайні положення: у першому тяга
    /// відтягнута від колії, в останньому підсунута до неї. Тяга тримає гостряки, тож в останньому положенні
    /// вони відведені від важеля. А відходять гостряки в бік, протилежний увімкненій гілці: щоб їхати
    /// ліворуч, до рамної рейки притиснутий правий. Отже останнє положення це гілка з боку важеля; туди ж
    /// тоді показує й покажчик на щоглі. Котра з двох гілок лежить з боку важеля, залежить від того, з якого
    /// боку колії він стоїть, тож від номера гілки положення напряму не залежить.
    /// Чиста логіка.
    /// </summary>
    public static class LeverPose
    {
        /// <summary>
        /// Де важіль між першим положенням (0) і останнім (1). position це увімкнена гілка, progress наскільки
        /// стрілка вже стала в це положення, від 0 до 1. branchAtLever це гілка з боку важеля
        /// (SectionLinker.BranchToward); якщо її не знайти (-1), важіль стоїть так, ніби це перша.
        /// </summary>
        public static double Thrown(int position, double progress, int branchAtLever)
        {
            // Де стрілка між першою гілкою (0) і другою (1)
            double value = position == 1 ? progress : 1 - progress;
            return branchAtLever == 1 ? value : 1 - value;
        }
    }
}
